#!/usr/bin/env python3
"""Builds a single-file distributable script for Siril's Scripts menu.

Siril's Scripts menu expects a single .py file, not an importable package.
We develop as a modular package (dg_patch_tool/) for testing, clean architecture,
and clarity, and this script flattens it into one self-contained .py file at build time.

How it works: every module's source is embedded verbatim in a dictionary,
keyed by its fully-qualified module name (e.g. "dg_patch_tool.ui.canvas_view").
A bootstrap at the top of the generated file registers an importlib meta_path finder/
loader that serves modules directly from that dictionary at runtime, so all imports
between modules resolve transparently without namespace collisions.
"""

from __future__ import annotations

import re
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PACKAGE_ROOT = REPO_ROOT / "dg_patch_tool"
OUTPUT_PATH = REPO_ROOT / "dist" / "DG_Patch_Tool.py"
ROOT_OUTPUT_PATH = REPO_ROOT / "DG_Patch_Tool.py"
EXCLUDE_DIR_NAMES = {"tests", "__pycache__"}

# User's Siril scripts directory on this machine
SIRIL_SCRIPTS_DIR = Path("/Users/daiangan/siril/scripts")
SIRIL_SCRIPTS_DIRS = [
    SIRIL_SCRIPTS_DIR,
    Path.home() / "Siril" / "scripts",
]

_HEADER_TEMPLATE = '''#!/usr/bin/env python3
# Script: DG_Patch_Tool
# Title: DG_Patch_Tool
# Description: External patch and heal tool for starless image cleanup in Siril
# Author: Daian Gan
"""DG_Patch_Tool — single-file build for the Siril Scripts menu.
Version: {version}

Author: Daian Gan

Auto-generated by build/bundle.py from the modular dg_patch_tool/ source tree.
Do NOT edit this file directly -- edit the source modules under dg_patch_tool/
and re-run `python build/bundle.py`.
"""

import sys
import importlib.abc
import importlib.util

# Ensure required packages in Siril's Python environment
try:
    import sirilpy
    if hasattr(sirilpy, "ensure_installed"):
        sirilpy.ensure_installed("PyQt6", "opencv-contrib-python", "numpy", "scipy")
except Exception:
    pass

_MODULE_SOURCES = {modules!r}
_PACKAGE_NAMES = {packages!r}


class _EmbeddedFinder(importlib.abc.MetaPathFinder, importlib.abc.Loader):
    def find_spec(self, fullname, path, target=None):
        if fullname not in _MODULE_SOURCES:
            return None
        return importlib.util.spec_from_loader(
            fullname, self, is_package=fullname in _PACKAGE_NAMES
        )

    def create_module(self, spec):
        return None  # use default module creation

    def exec_module(self, module):
        source = _MODULE_SOURCES[module.__name__]
        exec(compile(source, "<" + module.__name__ + ">", "exec"), module.__dict__)


sys.meta_path.insert(0, _EmbeddedFinder())

from dg_patch_tool.app import run

if __name__ == "__main__":
    sys.exit(run())
'''


def _module_name_and_kind(path: Path) -> tuple[str, bool]:
    rel = path.relative_to(PACKAGE_ROOT.parent)
    parts = list(rel.with_suffix("").parts)
    is_package = parts[-1] == "__init__"
    if is_package:
        parts = parts[:-1]
    return ".".join(parts), is_package


def collect_modules() -> tuple[dict[str, str], list[str]]:
    modules: dict[str, str] = {}
    packages: list[str] = []

    for path in sorted(PACKAGE_ROOT.rglob("*.py")):
        rel_parts = path.relative_to(PACKAGE_ROOT).parts
        if any(part in EXCLUDE_DIR_NAMES for part in rel_parts):
            continue
        name, is_package = _module_name_and_kind(path)
        modules[name] = path.read_text(encoding="utf-8")
        if is_package:
            packages.append(name)

    return modules, packages


def _extract_version(modules: dict[str, str]) -> str:
    match = re.search(r'__version__\s*=\s*"([^"]+)"', modules["dg_patch_tool"])
    if match is None:
        return "1.0.0"
    return match.group(1)


def build() -> Path:
    modules, packages = collect_modules()
    version = _extract_version(modules)
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    content = _HEADER_TEMPLATE.format(modules=modules, packages=packages, version=version)
    OUTPUT_PATH.write_text(content, encoding="utf-8")
    # Also update project root script
    ROOT_OUTPUT_PATH.write_text(content, encoding="utf-8")

    # Clean up legacy space-separated files if present
    for old_path in [REPO_ROOT / "dist" / "DG Patch Tool.py", REPO_ROOT / "DG Patch Tool.py"]:
        if old_path.exists():
            try:
                old_path.unlink()
            except Exception:
                pass

    return OUTPUT_PATH


def copy_to_siril_scripts(output_path: Path) -> list[Path]:
    """Copies the built script into detected Siril scripts folders."""
    copied: list[Path] = []
    for scripts_dir in SIRIL_SCRIPTS_DIRS:
        if scripts_dir.is_dir():
            # Clean up old space-separated file in Siril scripts folder
            old_script = scripts_dir / "DG Patch Tool.py"
            if old_script.exists():
                try:
                    old_script.unlink()
                except Exception:
                    pass
            dest = scripts_dir / output_path.name
            shutil.copy2(output_path, dest)
            copied.append(dest)
    return copied


if __name__ == "__main__":
    output = build()
    size_kb = output.stat().st_size / 1024
    print(f"Built single-file bundle: {output} ({size_kb:.1f} KB)")
    copied_list = copy_to_siril_scripts(output)
    for c in copied_list:
        print(f"Copied to Siril scripts folder: {c}")
